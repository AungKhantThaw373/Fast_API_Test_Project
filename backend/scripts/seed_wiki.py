"""Seed a story with many entities for the Phase 4 performance checks.

    cd backend && uv run python -m scripts.seed_wiki --email you@example.com --count 1000

It creates the entities, one alias and one fact each, spread over the chapters
that already exist in the story. Nothing is generated by an LLM, so this is
safe to run against the live database.
"""

import argparse
import asyncio
import random
import uuid

from sqlalchemy import select

from app.db import async_session
from app.models.app_models import User
from app.models.story_models import Chapter, Story
from app.models.wiki_models import Entity, EntityAlias, EntityFact
from app.services.entities import normalize_name

FIRST = ["Mira", "Hollis", "Sable", "Tessa", "Rook", "Juno", "Bram", "Wren", "Ivo", "Nell"]
LAST = ["Voss", "Alder", "Quill", "Marsh", "Fenn", "Hale", "Orr", "Lane", "Stone", "Wick"]
PLACES = ["Gate", "Yard", "Watch", "Mill", "Harbour", "Chapel", "Low Road", "Orchard"]
TYPES = ["character", "location", "item", "organization", "concept"]


def make_name(index: int) -> tuple[str, str]:
    if index % 4 == 0:
        return f"{random.choice(PLACES)} {index}", "location"
    return f"{random.choice(FIRST)} {random.choice(LAST)} {index}", "character"


async def seed(email: str, title: str, count: int) -> None:
    async with async_session() as session:
        user = (
            await session.execute(select(User).where(User.email == email))
        ).scalar_one_or_none()
        if user is None:
            raise SystemExit(f"No user with email {email}.")
        story = (
            await session.execute(
                select(Story).where(Story.owner_id == user.id, Story.title == title)
            )
        ).scalar_one_or_none()
        if story is None:
            raise SystemExit(f"No story titled {title!r} for that user.")
        chapters = list(
            await session.scalars(
                select(Chapter)
                .where(Chapter.story_id == story.id, Chapter.deleted_at.is_(None))
                .order_by(Chapter.chapter_number)
            )
        )
        if not chapters:
            raise SystemExit("That story has no chapters to cite.")

        for index in range(count):
            name, entity_type = make_name(index)
            entity = Entity(
                id=uuid.uuid4(),
                story_id=story.id,
                entity_type=random.choice(TYPES) if index % 7 == 0 else entity_type,
                name=name,
                canonical_name=normalize_name(name) or name.casefold(),
                summary=f"Seeded entry {index} for performance checks.",
                status="active",
                first_chapter_number=chapters[0].chapter_number,
                last_chapter_number=chapters[-1].chapter_number,
            )
            session.add(entity)
            session.add(
                EntityAlias(
                    id=uuid.uuid4(),
                    entity_id=entity.id,
                    alias=name.split(" ")[0],
                    normalized_alias=normalize_name(name.split(" ")[0]) or name.split(" ")[0].casefold(),
                    alias_type="name",
                )
            )
            chapter = chapters[index % len(chapters)]
            session.add(
                EntityFact(
                    id=uuid.uuid4(),
                    entity_id=entity.id,
                    predicate="seeded detail",
                    value_text=f"value {index}",
                    value_type="text",
                    status="accepted" if index % 3 else "proposed",
                    confidence=70 + index % 30,
                    chapter_id=chapter.id,
                    line_start=1,
                    quote="Seeded for performance checks.",
                    created_by="human",
                )
            )
        await session.commit()
        print(f"Seeded {count} entities into {title!r}.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--email", required=True)
    parser.add_argument("--title", default="Perf")
    parser.add_argument("--count", type=int, default=1000)
    args = parser.parse_args()
    asyncio.run(seed(args.email, args.title, args.count))


if __name__ == "__main__":
    main()
